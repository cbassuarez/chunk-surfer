// Exact authored corrective curves for the study-only additive presentation.
// Avoids overriding animated GLB weights with renderer cue zeros.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { parseCharacterAsset } from '../../src/render/character-asset.js';
const path = new URL('../../public/assets/pressure-character.glb', import.meta.url);
const bytes = readFileSync(path), asset = parseCharacterAsset(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
const entry = asset.entries.find(e => e.name === 'pressure_body');
const curves = {};
for (const name of asset.clips.keys()) {
  const clip = asset.clips.get(name), channel = clip.channels.find(c => c.path === 'weights' && c.node === entry.node);
  if (!channel || channel.interpolation !== 'LINEAR') throw Error('Study requires exact linear authored morph channel');
  curves[name] = { duration: clip.duration, times: Array.from(channel.times), values: Array.from(channel.values), width: channel.width };
}
const data = { source: 'public/assets/pressure-character.glb', sha256: createHash('sha256').update(bytes).digest('hex'), names: entry.morphNames, curves };
writeFileSync(new URL('../../artifacts/hush-motion-study/traction-morph-curves.js', import.meta.url),
  '// Generated by export-hush-motion-morph-curves.mjs from actual GLB channels.\nexport const TRACTION_MORPH_CURVES = ' + JSON.stringify(data) + ';\n');
console.log(JSON.stringify({ channels: Object.keys(curves), sha256: data.sha256 }));
