"""The ground motion under Earthfall, from a real strong-motion record.

2019 Ridgecrest Mw 7.1 (2019-07-06 03:19:53 UTC) at CI.CLC, China Lake,
~11 km hypocentral (S-P 1.40 s). The three 100 Hz accelerometer channels
HN[ENZ] in ./earthfall-record were fetched from the SCEDC FDSN dataselect
service for 03:19:50-03:21:20 UTC:

  https://service.scedc.caltech.edu/fdsnws/dataselect/1/query?net=CI&sta=CLC&cha=HNE&starttime=2019-07-06T03:19:50&endtime=2019-07-06T03:21:20

Sensitivities are the channel values from the FDSN station service. Processing:
counts / sensitivity -> demean, linear detrend, 3% taper -> 4-pole zero-phase
Butterworth 0.3-5 Hz. Displacement is the double integral, re-filtered in the
same band after each integration. The window starts 1.5 s before the P pick and
is resampled to 60 Hz.

Needs ObsPy (pip install obspy). Writes src/data/generated/source-earthfall-record.js.
Run: python3 tools/chunk_surfer/build-earthfall-record.py
"""
import json
from pathlib import Path

import numpy as np
from obspy import read
from obspy.signal.trigger import classic_sta_lta

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SENSITIVITY = {'HNE': 213945.4273635581, 'HNN': 213808.5679825483, 'HNZ': 213740.13829204338}
BAND = dict(freqmin=0.3, freqmax=5.0, corners=4, zerophase=True)
RATE, WINDOW, LEAD = 60, 32.0, 1.5

acc, raw = {}, {}
for channel, counts in SENSITIVITY.items():
    stream = read(str(HERE / 'earthfall-record' / f'{channel}.mseed'))
    stream.merge(fill_value=0)
    trace = stream[0]
    trace.data = trace.data.astype(float) / counts
    trace.detrend('demean'); trace.detrend('linear'); trace.taper(0.03)
    raw[channel] = trace.copy()
    trace.filter('bandpass', **BAND)
    acc[channel] = trace

rate = raw['HNZ'].stats.sampling_rate
ratio = classic_sta_lta(raw['HNZ'].data, int(0.2 * rate), int(5 * rate))
p = int(np.argmax(ratio > 4))
horizontal = np.hypot(acc['HNE'].data, acc['HNN'].data)
s = p + int(np.argmax(horizontal[p:] > 0.45 * horizontal.max()))

displacement = {}
for channel, trace in acc.items():
    d = trace.copy()
    d.integrate(); d.filter('bandpass', **BAND)
    d.integrate(); d.filter('bandpass', **BAND)
    displacement[channel] = d.data

start = max(0, p - int(LEAD * rate))
index = np.arange(start, min(start + int(WINDOW * rate), len(raw['HNZ'].data)))
seconds = (index - start) / rate
grid = np.arange(0, seconds[-1], 1 / RATE)
resample = lambda values: [round(float(v), 5) for v in np.interp(grid, seconds, values[index])]

record = {
    'event': 'Ridgecrest, California, Mw 7.1, 2019-07-06 03:19:53 UTC',
    'station': 'CI.CLC (China Lake), HN[ENZ] accelerometers, ~11 km hypocentral',
    'source': 'SCEDC FDSN dataselect; sensitivities from the FDSN station service',
    'processing': 'counts/sensitivity, demean, detrend, 3% taper, 4-pole zero-phase Butterworth 0.3-5 Hz; displacement double-integrated and re-filtered; 60 Hz',
    'rate': RATE, 'samples': len(grid),
    'pAt': round((p - start) / rate, 3), 'sAt': round((s - start) / rate, 3),
    'peakAccelerationMs2': {c: round(float(np.abs(acc[c].data[index]).max()), 4) for c in SENSITIVITY},
    'peakDisplacementM': {c: round(float(np.abs(displacement[c][index]).max()), 4) for c in SENSITIVITY},
    # m/s^2 and m. East, north, up as recorded.
    'acceleration': {'east': resample(acc['HNE'].data), 'north': resample(acc['HNN'].data), 'up': resample(acc['HNZ'].data)},
    'displacement': {'east': resample(displacement['HNE']), 'north': resample(displacement['HNN']), 'up': resample(displacement['HNZ'])},
}
out = ROOT / 'src' / 'data' / 'generated' / 'source-earthfall-record.js'
out.write_text('// Generated by tools/chunk_surfer/build-earthfall-record.py from a real\n'
               '// strong-motion record; do not hand edit.\n'
               f'export const SOURCE_EARTHFALL_RECORD=Object.freeze({json.dumps(record, separators=(",", ":"))});\n')
print(f'wrote {out.relative_to(ROOT)}: {len(grid)} samples, P {record["pAt"]} s, S {record["sAt"]} s')
