// The retained standing costume has almost rigid, opposite influences on
// adjoining crotch and underarm vertices. Deep crouches expose that as long
// triangular seams. Diffuse the garment weights over its own rest-space cloth
// neighbourhood, including duplicate UV vertices, before limiting to four
// influences. Body, fingers, face and shared source assets are unchanged.
function relaxGarmentWeights(mesh) {
  const radius = .055, cell = radius, count = mesh.positions.length / 3, grid = new Map();
  const key = (x, y, z) => `${x},${y},${z}`;
  const at = vertex => mesh.positions.slice(vertex * 3, vertex * 3 + 3);
  const cells = [];
  for (let v = 0; v < count; v++) {
    const c = at(v).map(n => Math.floor(n / cell)); cells.push(c);
    const k = key(...c); if (!grid.has(k)) grid.set(k, []); grid.get(k).push(v);
  }
  const neighbours = [];
  for (let v = 0; v < count; v++) {
    const p = at(v), [x, y, z] = cells[v], rows = [];
    for (let dx = -1; dx <= 1; dx++) for (let dy = -1; dy <= 1; dy++) for (let dz = -1; dz <= 1; dz++)
      for (const other of grid.get(key(x + dx, y + dy, z + dz)) || []) {
        const q = at(other), distance = Math.hypot(...q.map((n, i) => n - p[i]));
        if (distance < radius) rows.push([other, Math.exp(-distance * distance / (radius * radius * .32))]);
      }
    neighbours.push(rows);
  }
  let weights = Array.from({ length: count }, (_, v) => {
    const pairs = new Map();
    for (let k = 0; k < 4; k++) if (mesh.skinWeight[v * 4 + k]) pairs.set(mesh.skinIndex[v * 4 + k], mesh.skinWeight[v * 4 + k]);
    return pairs;
  });
  for (let pass = 0; pass < 5; pass++) weights = neighbours.map((rows, v) => {
    const sum = new Map(), total = rows.reduce((n, row) => n + row[1], 0);
    for (const [other, influence] of rows) for (const [joint, weight] of weights[other]) sum.set(joint, (sum.get(joint) || 0) + weight * influence / total * .76);
    for (const [joint, weight] of weights[v]) sum.set(joint, (sum.get(joint) || 0) + weight * .24);
    return new Map([...sum].filter(([, weight]) => weight > .00001));
  });
  weights.forEach((weights, v) => {
    const rows = [...weights].sort((a, b) => b[1] - a[1]).slice(0, 4), total = rows.reduce((n, row) => n + row[1], 0);
    while (rows.length < 4) rows.push([0, 0]);
    for (let k = 0; k < 4; k++) { mesh.skinIndex[v * 4 + k] = rows[k][0]; mesh.skinWeight[v * 4 + k] = rows[k][1] / total; }
  });
}
