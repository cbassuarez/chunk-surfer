function normals(positions, indices) {
  const out = Array(positions.length).fill(0);
  for (let k = 0; k < indices.length; k += 3) {
    const [a, b, c] = indices.slice(k, k + 3), ab = [0, 1, 2].map(q => positions[b * 3 + q] - positions[a * 3 + q]), ac = [0, 1, 2].map(q => positions[c * 3 + q] - positions[a * 3 + q]);
    const n = [ab[1] * ac[2] - ab[2] * ac[1], ab[2] * ac[0] - ab[0] * ac[2], ab[0] * ac[1] - ab[1] * ac[0]];
    for (const vertex of [a, b, c]) for (let q = 0; q < 3; q++) out[vertex * 3 + q] += n[q];
  }
  for (let k = 0; k < out.length; k += 3) { const d = Math.hypot(...out.slice(k, k + 3)) || 1; for (let q = 0; q < 3; q++) out[k + q] = round(out[k + q] / d); }
  return out;
}

