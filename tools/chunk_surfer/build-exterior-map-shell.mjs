// Project the actual exterior model, not the interior floorplan, onto the
// one-metre survey sheet. Thin decoration disappears at this scale; roofed
// wings, courts, links and the service aperture retain their source geometry.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseGlb,meshFingerprint} from './rebuild-tree-crowns.mjs';
import {readExteriorAccessor,extractExteriorCollision} from './build-exterior-collision.mjs';
import {CONSERVATORY_PROPS} from '../../src/data/conservatory-props.js';
const inside=(x,z,a,b,c)=>{const sign=(p,q)=>(x-q[0])*(p[2]-q[2])-(p[0]-q[0])*(z-q[2]),s=[sign(a,b),sign(b,c),sign(c,a)];return !(s.some(n=>n<-.00001)&&s.some(n=>n>.00001));};
export function extractExteriorMapShell(pack){
  const name='conservatory_west_elevation',mesh=pack.json.meshes.find(m=>m.name===name),cells=new Set();
  const prop=CONSERVATORY_PROPS.find(p=>p.id==='bay-west-elevation');
  if(!mesh)throw Error(`Missing ${name}`);
  extractExteriorCollision(pack,[name]); // validates baked source node transforms.
  let projectedTriangles=0;
  for(const primitive of mesh.primitives){
    const vertices=readExteriorAccessor(pack,primitive.attributes.POSITION),indices=readExteriorAccessor(pack,primitive.indices).flat();
    for(let i=0;i<indices.length;i+=3){
      const[a,b,c]=indices.slice(i,i+3).map(n=>{const[x,y,z]=vertices[n],co=Math.cos(prop.yaw||0),si=Math.sin(prop.yaw||0),scale=prop.scale||1;return[prop.x+(x*co-z*si)*scale,y*scale,prop.y+(x*si+z*co)*scale];});
      if(Math.min(a[1],b[1],c[1])<2.5)continue;
      const area=(b[0]-a[0])*(c[2]-a[2])-(b[2]-a[2])*(c[0]-a[0]);if(Math.abs(area)<.00001)continue;
      projectedTriangles++;
      for(let x=Math.floor(Math.min(a[0],b[0],c[0]));x<Math.ceil(Math.max(a[0],b[0],c[0]));x++)for(let z=Math.floor(Math.min(a[2],b[2],c[2]));z<Math.ceil(Math.max(a[2],b[2],c[2]));z++)if(inside(x+.5,z+.5,a,b,c))cells.add(`${x},${z}`);
    }
  }
  const rows=new Map();for(const key of cells){const[x,z]=key.split(',').map(Number);if(!rows.has(z))rows.set(z,[]);rows.get(z).push(x);}
  const runs=[...rows].sort((a,b)=>a[0]-b[0]).flatMap(([z,xs])=>{xs.sort((a,b)=>a-b);const row=[];let x0=xs[0],x1=x0;for(const x of xs.slice(1)){if(x===x1+1)x1=x;else{row.push([z,x0,x1]);x0=x1=x;}}row.push([z,x0,x1]);return row;});
  return{version:1,asset:'public/assets/conservatory-props.glb',mesh:name,propId:'bay-west-elevation',origin:{x:prop.x,z:prop.y,yaw:prop.yaw||0,scale:prop.scale||1},meshSha256:meshFingerprint(pack,mesh),resolutionM:1,
    derivation:'centre coverage of projected exact mesh triangles wholly above 2.5m; roof/capping silhouette only; no interior rooms or route topology',projectedTriangles,cellCount:cells.size,runs};
}
export function buildExteriorMapShell({root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..'),write=true,
  assetPath=path.join(root,'public/assets/conservatory-props.glb'),outputPath=path.join(root,'src/data/generated/exterior-map-shell.js')}={}){
  const data=extractExteriorMapShell(parseGlb(fs.readFileSync(assetPath)));
  if(write){
    fs.mkdirSync(path.dirname(outputPath),{recursive:true});
    fs.writeFileSync(outputPath,`// Generated by tools/chunk_surfer/build-exterior-map-shell.mjs from the actual exterior mesh.\nexport const EXTERIOR_MAP_SHELL=Object.freeze(${JSON.stringify(data)});\n`);
  }
  return data;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){const data=buildExteriorMapShell();console.log(JSON.stringify({...data,runs:`${data.runs.length} projected runs`},null,2));}
