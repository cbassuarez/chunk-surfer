import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { parseCharacterAsset, sampleCharacterPose } from '../../src/render/character-asset.js';
import { HUSH_BATTLE_VIEW_RISE, HUSH_BATTLE_VIEW_DISTANCE } from '../../src/render/hush-battle-camera.js';

const input = process.argv[2] || 'public/assets/hush-density.glb';
const output = process.argv[3] || 'src/render/hush-battle-fallback-data.js';
const bytes = readFileSync(input);
const asset = parseCharacterAsset(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
const body = asset.entries.find(entry => entry.name === 'hush_density_volume');
const { bones } = sampleCharacterPose(asset, body, { clip: 'pressure_hold' });
const bounds = { x: -.64, y: -1.10, width: 1.28, height: 2.27 };
const step = .014;
const columns = Math.ceil(bounds.width / step), rows = Math.ceil(bounds.height / step);
const cells = new Uint8Array(columns * rows);
const incline = Math.atan2(HUSH_BATTLE_VIEW_RISE, HUSH_BATTLE_VIEW_DISTANCE);
const scale = 2.18 / 2.05;

function project(primitive, vertex) {
  const [x, y, z] = primitive.positions.subarray(vertex * 3, vertex * 3 + 3);
  let px = 0, py = 0, pz = 0;
  for (let slot = 0; slot < 4; slot++) {
    const offset = vertex * 4 + slot;
    const weight = primitive.weights[offset], start = primitive.joints[offset] * 16;
    if (weight === 0) continue;
    px += weight * (bones[start] * x + bones[start + 4] * y + bones[start + 8] * z + bones[start + 12]);
    py += weight * (bones[start + 1] * x + bones[start + 5] * y + bones[start + 9] * z + bones[start + 13]);
    pz += weight * (bones[start + 2] * x + bones[start + 6] * y + bones[start + 10] * z + bones[start + 14]);
  }
  // The source faces -Z, so the battle presentation rotates it by pi.
  return [-px * scale, -(py * Math.cos(incline) + pz * Math.sin(incline)) * scale];
}

const edge = (a, b, x, y) => (b[0] - a[0]) * (y - a[1]) - (b[1] - a[1]) * (x - a[0]);
for (const primitive of body.primitives) {
  const points = Array.from({ length: primitive.vertexCount }, (_, i) => project(primitive, i));
  for (let index = 0; index < primitive.indices.length; index += 3) {
    const a = points[primitive.indices[index]];
    const b = points[primitive.indices[index + 1]];
    const c = points[primitive.indices[index + 2]];
    const area = edge(a, b, ...c);
    if (Math.abs(area) < 1e-10) continue;
    const sign = Math.sign(area);
    const toCellX = x => (x - bounds.x) / step;
    const toCellY = y => (y - (bounds.y - bounds.height / 2)) / step;
    const startX = Math.max(0, Math.floor(toCellX(Math.min(a[0], b[0], c[0]))));
    const endX = Math.min(columns - 1, Math.floor(toCellX(Math.max(a[0], b[0], c[0]))));
    const startY = Math.max(0, Math.floor(toCellY(Math.min(a[1], b[1], c[1]))));
    const endY = Math.min(rows - 1, Math.floor(toCellY(Math.max(a[1], b[1], c[1]))));
    for (let row = startY; row <= endY; row++) for (let column = startX; column <= endX; column++) {
      const x = bounds.x + (column + .5) * step;
      const y = bounds.y - bounds.height / 2 + (row + .5) * step;
      if (edge(a, b, x, y) * sign >= 0 && edge(b, c, x, y) * sign >= 0 && edge(c, a, x, y) * sign >= 0)
        cells[row * columns + column] = 1;
    }
  }
}

const lines = [];
for (let row = 0; row < rows; row++) {
  const spans = [];
  for (let column = 0; column < columns;) {
    if (!cells[row * columns + column]) { column++; continue; }
    const start = column++;
    while (column < columns && cells[row * columns + column]) column++;
    spans.push(start, column - start);
  }
  lines.push(spans);
}
const hash = createHash('sha256').update(bytes).digest('hex');
writeFileSync(output, [
  '// Generated by tools/chunk_surfer/build-hush-battle-fallback.mjs.',
  '// Opaque coverage of the authored held mesh. No separate fallback anatomy.',
  `export const HUSH_FALLBACK_SOURCE_SHA256 = '${hash}';`,
  `export const HUSH_FALLBACK_STEP = ${step};`,
  `export const HUSH_FALLBACK_ORIGIN = [${bounds.x}, ${bounds.y - bounds.height / 2}];`,
  'export const HUSH_FALLBACK_SPANS = [',
  ...lines.map(row => '  [' + row.join(', ') + '],'),
  '];',
  '',
].join('\n'));
