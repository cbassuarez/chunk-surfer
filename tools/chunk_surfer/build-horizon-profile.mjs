#!/usr/bin/env node
// WHAT THE TAPE IS DOING, SLICE BY SLICE.
//
// The horizon was a straight walk down a tube: 512 cells of flat floor, hard
// walls at a fixed width, and one thing to look at. Holding W for two minutes.
//
// But the recording is not uniform, and it never was. Measured off the shipped
// bake, the picture's bright mass WANDERS — its luminance centre of mass swings
// between -23 and +18 across the tape — and there is a long middle stretch
// where the codec has fallen apart, up to 74% macroblock damage, with clean
// ends either side of it. That is shape, and it is shape the recording itself
// authored. Nothing had ever read it.
//
// So this reads it. One small file, derived from horizon-tape.bin — no source
// video required, which matters because the source is not in the repo — giving
// per slice:
//
//   com    where the light is, across the corridor
//   spread how wide the picture's substance actually is
//   mosh   how damaged this part of the tape is, 0..1
//   lum    how much picture there is at all
//
// The runtime shapes the walk with it (the floor follows the picture, and the
// edges are soft because the picture has no edges, only an ending) and the
// renderer can lean on it too.
//
// Usage:  node tools/chunk_surfer/build-horizon-profile.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const IN_JSON = path.join(ROOT, 'public/assets/horizon-tape.json');
const IN_BIN = path.join(ROOT, 'public/assets/horizon-tape.bin');
// Emitted as a module rather than an asset: both the runtime (which shapes the
// walk with it) and the renderer want it, neither wants to wait for a fetch to
// know where the floor is, and five kilobytes is not worth a load order.
const OUT = path.join(ROOT, 'src/data/generated/horizon-profile.js');

const manifest = JSON.parse(fs.readFileSync(IN_JSON, 'utf8'));
const bytes = fs.readFileSync(IN_BIN);
const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
const stride = manifest.recordBytes;
const posScale = manifest.posScale;

const round = (v, n = 2) => Number(v.toFixed(n));

const slices = manifest.ranges.map((range) => {
  if (!range.count) return { com: 0, spread: 0, mosh: 0, lum: 0 };
  let weight = 0, weighted = 0, mosh = 0, lumSum = 0;
  const xs = [];
  for (let i = range.first; i < range.first + range.count; i += 1) {
    const o = i * stride;
    const x = view.getInt16(o + 0, true) / posScale;
    const lum = bytes[o + 8] * 0.2126 + bytes[o + 9] * 0.7152 + bytes[o + 10] * 0.0722;
    if (bytes[o + 13] === 2) mosh += 1;
    weight += lum; weighted += lum * x; lumSum += lum;
    xs.push({ x, lum });
  }
  const com = weight > 0 ? weighted / weight : 0;
  // Spread is the luminance-weighted deviation from the centre of mass: how
  // much of the frame is actually carrying picture, rather than how wide the
  // frame is. A slice with everything piled on one side is narrow even though
  // its extent is the full 128.
  let variance = 0;
  for (const s of xs) variance += s.lum * (s.x - com) ** 2;
  const spread = weight > 0 ? Math.sqrt(variance / weight) : 0;
  return {
    com: round(com),
    spread: round(spread),
    mosh: round(mosh / range.count, 3),
    lum: round(lumSum / range.count / 255, 3),
  };
});

// A hard per-slice centre line would jitter the floor out from under the body,
// because adjacent slices are a second of video apart and the picture cuts.
// Smoothed wide: what is wanted is the DRIFT of the recording, not its edits.
const smooth = (values, radius) => values.map((_, i) => {
  let sum = 0, n = 0;
  for (let k = -radius; k <= radius; k += 1) {
    const j = i + k;
    if (j < 0 || j >= values.length) continue;
    const w = 1 - Math.abs(k) / (radius + 1);
    sum += values[j] * w; n += w;
  }
  return round(sum / n);
});

const profile = {
  schema: 1,
  id: 'chunk-surf.horizon-profile',
  source: 'horizon-tape.bin',
  slices: slices.length,
  sliceMetres: manifest.sliceMetres,
  span: manifest.span,
  com: smooth(slices.map((s) => s.com), 7),
  spread: smooth(slices.map((s) => s.spread), 5),
  mosh: smooth(slices.map((s) => s.mosh), 3),
  lum: smooth(slices.map((s) => s.lum), 3),
};

const header = `// GENERATED by tools/chunk_surfer/build-horizon-profile.mjs — do not edit by hand.
//
// WHAT THE TAPE IS DOING, SLICE BY SLICE, read back off the shipped bake.
//
// The horizon used to be a straight walk down a tube. The recording it is made
// of is not straight: its bright mass wanders across the corridor, and a long
// middle stretch of it has fallen apart into macroblock damage with clean ends
// either side. This is that shape, measured, so the walk can follow the picture
// instead of ignoring it.
//
//   com     where the light is, across the corridor, in tape units
//   spread  how wide the picture's substance is at that depth
//   mosh    0..1, how damaged this part of the tape is
//   lum     0..1, how much picture there is at all
//
// All four are smoothed along the tape: adjacent slices are a second of video
// apart and the source cuts, and the walk wants the recording's DRIFT, not its
// edits — a hard per-slice centre line would pull the floor out from under the
// body every step.
`;
fs.writeFileSync(OUT, `${header}export const HORIZON_PROFILE = Object.freeze(${JSON.stringify(profile)});\n`);
const drift = profile.com;
console.log(`horizon profile: ${profile.slices} slices`);
console.log(`  drift  ${Math.min(...drift).toFixed(1)} .. ${Math.max(...drift).toFixed(1)} across the corridor`);
console.log(`  spread ${Math.min(...profile.spread).toFixed(1)} .. ${Math.max(...profile.spread).toFixed(1)}`);
console.log(`  mosh   ${Math.min(...profile.mosh).toFixed(2)} .. ${Math.max(...profile.mosh).toFixed(2)}`);
console.log(`  wrote  ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes)`);
