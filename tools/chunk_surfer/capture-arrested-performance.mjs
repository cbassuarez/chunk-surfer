// Clear-floor acceptance capture from the actual simulation, independent of a
// browser clock or camera. The review only plays its bounded saved descriptors.
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import * as PRES from '../../src/game/presence.js';
import { createPressurePerformance } from '../../src/game/pressure-performance.js';
import { packShadowFrames, unpackShadowFrames } from '../../src/causal/tape.js';

let now=100000,random=4417;
const previousPerformance=globalThis.performance,previousRandom=Math.random;
Object.defineProperty(globalThis,'performance',{configurable:true,value:{now:()=>now}});
Math.random=()=>{random=(Math.imul(random,1664525)+1013904223)>>>0;return random/4294967296;};
try{
  PRES.loadPresenceState({awareness:0,caughtCount:0});
  PRES.spawnAtCell(-.5,5.5,{sector:'arrested-clear-floor-review',gaitSeed:4417});
  const driver=createPressurePerformance();driver.reset({seed:4417});
  const frames=[],transitions=[],seconds=24,dt=1/60;
  let lastPhase=null,lastSaved=-1;
  for(let i=0;i<=seconds/dt;i++){
    const t=i*dt;now=100000+t*1000;
    // Two fixed acoustic sources, offered only when a sound occurs. The
    // observer is elsewhere and never supplies the remembered destination.
    if(i%180===0)PRES.offerSoundTarget({position:{x:t<12?-.5:5.5,y:-2.5},level:1,confidence:1,
      priority:.96,expiresAt:now+4500,reason:'REVIEW_STATIONARY_SOUND'});
    PRES.updatePresence(i?dt:0,-.5,-7.5,null,{suppressContact:true});
    const p=PRES.presenceState(),gait=structuredClone(p.gait);
    assert.ok(gait,'Arrested hunt must be generated by the actual gait controller');
    const motion=p.behaviorMode==='chase'?'hunt':['listen','limp','investigate'].includes(p.behaviorMode)?p.behaviorMode:'idle';
    const performance=driver.tick(i?dt:0,{primary:{id:'arrested-review:4417',role:'live-pressure',
      x:p.x,y:p.y,velocityX:p.velocityX,velocityY:p.velocityY,heading:gait.heading,gait,motion,
      floorH:0,strength:1,radiusM:6.4,heightM:2.18,widthM:.68}});
    const phase=`${gait.cycle}:${gait.phase}`;
    const changed=phase!==lastPhase;
    if(changed)transitions.push({time:t,cycle:gait.cycle,phase:gait.phase,clip:performance.primary.performance.clip,
      x:p.x,y:p.y,heading:gait.heading});
    if(changed||t-lastSaved>=.049||i===seconds/dt){
      frames.push({t:Math.round(t*1000),x:-.5,y:-7.5,floorH:0,yaw:0,pitch:0,spaceId:'conservatory',
        roomId:'pressure-review',pressurePresentation:performance});lastSaved=t;
    }
    lastPhase=phase;
  }
  const fixture={schema:1,kind:'pressure-character-review',seconds,origin:'actual Presence clear-floor simulation',
    seed:4417,transitions,shadowFrames:packShadowFrames(frames)};
  const decoded=unpackShadowFrames(JSON.parse(JSON.stringify(fixture.shadowFrames)));
  assert.equal(decoded.length,frames.length);
  assert.ok(transitions.some(p=>p.phase==='load')&&transitions.some(p=>p.phase==='advance'));
  const output=new URL('../../artifacts/pressure-character/arrested-performance.json',import.meta.url);
  writeFileSync(output,JSON.stringify(fixture,null,2)+'\n');
  console.log(JSON.stringify({seconds,frames:frames.length,transitions:transitions.length,
    travelMetres:Math.hypot((frames.at(-1).pressurePresentation.primary.x+.5)*.5,
      (frames.at(-1).pressurePresentation.primary.y-5.5)*.5),output:output.pathname},null,2));
}finally{
  PRES.despawn();Math.random=previousRandom;
  Object.defineProperty(globalThis,'performance',{configurable:true,value:previousPerformance});
}
