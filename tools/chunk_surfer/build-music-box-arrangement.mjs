// Clair de lune, bars 1-8, arranged for a small cylinder music box.
//
// Source: assets/music-box/clair-de-lune.mid (Mutopia 1778, public domain; see
// assets/music-box/provenance.json). A cylinder box has one steel tine per
// pitch and no sustain, so the arrangement keeps the piano's onsets, moves the
// whole texture up an octave into a comb's range (Bb4-A6), folds anything lower
// up, merges unisons, and keeps at most three tines struck at once: the top
// voice (the tune) always, then the lowest, then one between.
//
//   node tools/chunk_surfer/build-music-box-arrangement.mjs
import fs from 'node:fs';
import { readMidi } from './lib-midi-notes.mjs';

const ROOT = new URL('../../', import.meta.url);
const MIDI = new URL('assets/music-box/clair-de-lune.mid', ROOT);
const OUT = new URL('src/data/clair-de-lune-music-box.js', ROOT);
const BARS = 8, BAR_SECONDS = 4.2, LOW = 70, HIGH = 93;

const midi = readMidi(MIDI.pathname), bar = midi.division * 4.5;
const byTick = new Map();
for (const n of midi.notes) {
  if (n.tick >= bar * BARS) continue;
  let p = n.pitch + 12;
  while (p < LOW) p += 12;
  while (p > HIGH) p -= 12;
  if (!byTick.has(n.tick)) byTick.set(n.tick, { tick: n.tick, notes: new Map() });
  const at = byTick.get(n.tick);
  // The right hand's top note is the tune; keep the highest-voice claim.
  const melody = n.track === 1;
  if (!at.notes.has(p) || melody) at.notes.set(p, { pitch: p, rightHand: melody || at.notes.get(p)?.rightHand });
}
const events = [];
for (const at of [...byTick.values()].sort((a, b) => a.tick - b.tick)) {
  const pitches = [...at.notes.values()].sort((a, b) => b.pitch - a.pitch);
  const top = pitches.find((n) => n.rightHand) || pitches[0];
  const rest = pitches.filter((n) => n !== top);
  const keep = [top, ...(rest.length ? [rest.at(-1)] : []), ...(rest.length > 2 ? [rest[Math.floor((rest.length - 1) / 2)]] : [])];
  const seconds = +(at.tick / bar * BAR_SECONDS).toFixed(4);
  for (const n of keep) events.push({ at: seconds, pitch: n.pitch, voice: n === top ? 'tune' : 'inner' });
}
const pitches = [...new Set(events.map((e) => e.pitch))].sort((a, b) => a - b);
const text = `// Generated by tools/chunk_surfer/build-music-box-arrangement.mjs. Do not edit.
// Debussy, Clair de lune (Suite bergamasque L. 75), bars 1-${BARS}, from the public
// domain Mutopia edition 1778 (E. Fromont, 1905): assets/music-box/provenance.json.
// at = score seconds at ${BAR_SECONDS} s per 9/8 bar, pitch = MIDI note on the comb.
export const CLAIR_DE_LUNE_SOURCE = Object.freeze({ mutopia: 1778, edition: 'E. Fromont, 1905', license: 'Public Domain', bars: ${BARS}, barSeconds: ${BAR_SECONDS} });
export const CLAIR_DE_LUNE_SCORE_SECONDS = ${(BARS * BAR_SECONDS).toFixed(4)};
export const CLAIR_DE_LUNE_COMB = Object.freeze(${JSON.stringify(pitches)});
export const CLAIR_DE_LUNE_EVENTS = Object.freeze([
${events.map((e) => `  Object.freeze(${JSON.stringify(e)}),`).join('\n')}
]);
`;
fs.writeFileSync(OUT, text);
console.log(JSON.stringify({ events: events.length, onsets: byTick.size, comb: pitches.length, low: pitches[0], high: pitches.at(-1) }));
