import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {UNRAVELLING_GLSL} from '../src/render/source-unravelling-shader.js';
const renderer=readFileSync(new URL('../src/render/r3d.js',import.meta.url),'utf8');
assert.match(renderer,/RAIN_GLSL\+UNRAVELLING_GLSL/);
assert.doesNotMatch(UNRAVELLING_GLSL,/Time|Boil|clock|sin\([^)]*amount/);
assert.match(UNRAVELLING_GLSL,/remnant=step\(\.91,seed\)/);
assert.match(UNRAVELLING_GLSL,/sector=floor\(p\.xz/);
assert.doesNotMatch(renderer,/horizon3d\.js|drawHorizon\(|horizon-tape\.bin/);
console.log('shared Source decay shader specs passed');
