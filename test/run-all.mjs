export const TEST_FILES = Object.freeze(tests);

export function runTests(files = TEST_FILES, { spawn = spawnSync, log = console.log, error = console.error } = {}) {
  const failures=[];
  for (const [index, file] of files.entries()) {
    log(`RUN ${index + 1}/${files.length} ${file}`);
    const result = spawn(process.execPath, [file], {
      cwd: process.cwd(),
      stdio: 'inherit',
      // A leaked timer/socket or stuck child is a visible failure, never a
      // forced successful exit after an otherwise green TAP summary.
      // The acquisition contract performs35 real building-wide path searches.
      // Completed profiles take189–443s depending on concurrent load. Keep
      // every route assertion with a bounded ten-minute allowance for slower
      // platform runners; all other files retain the three-minute watchdog.
      timeout: file === 'test/acquisition-props.test.mjs' ? 600_000 : 180_000,
    });
    if (result.error || result.signal || result.status !== 0) {
      error(`FAILED ${file}: ${result.error?.message || result.signal || `exit ${result.status}`}`);
      failures.push({file,status:result.status||1});
    }
  }
  if(failures.length){
    error(`${failures.length}/${files.length} test files failed: ${failures.map(f=>f.file).join(', ')}`);
    return failures[0].status;
  }
  log(`all ${files.length} test files passed`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === '--list') console.log(JSON.stringify({ tests: TEST_FILES, externalTests: EXTERNAL_TEST_FILES }));
  else process.exitCode = runTests();
}
