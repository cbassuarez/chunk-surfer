#!/usr/bin/env python3
# Regenerates src/data/gamecontrollerdb.js from the raw database.
# Usage: python3 scripts/parse-gamecontrollerdb.py < gamecontrollerdb.txt
import sys,json
rows=[]
for line in sys.stdin:
    line=line.strip()
    if not line or line.startswith('#'): continue
    parts=line.split(',')
    if len(parts)<3: continue
    guid,name=parts[0],parts[1]
    entry={'guid':guid,'name':name}
    for tok in parts[2:]:
        if not tok or ':' not in tok: continue
        key,val=tok.split(':',1)
        if key in ('platform','crc','hint'): continue
        entry[key]=val
    rows.append(entry)
db={}
for r in rows: db.setdefault(r['guid'],r)
print("// The SDL GameControllerDB, vendored and parsed (regenerated by", file=sys.stderr)
open('src/data/gamecontrollerdb.js','w').write(
"// The SDL GameControllerDB, vendored and parsed (src/data/gamecontrollerdb.txt\n"
"// is the raw database; regenerate with scripts/parse-gamecontrollerdb.py).\n"
"// https://github.com/mdqinc/SDL_GameControllerDB (zlib licence)\n"
"export const GAMECONTROLLER_DB=Object.freeze("+json.dumps(db,separators=(',',':'))+");\n")
print('wrote',len(db),'entries')
