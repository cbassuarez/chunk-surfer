// THE VAN ICON, from one geometry source.
//
// assets/brand/van-icon-geometry.json owns the van's contours. This script
// turns them into (a) the SVG master that renders the cut-out PNG the icon
// pipeline packages, and (b) the ObjC include the running Dock assembly
// draws from, so the static icon and the launch animation can never drift
// apart. Deterministic: rerunning it with the same JSON writes the same
// bytes, which test/app-icon-readability.spec.mjs asserts.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const geometry = JSON.parse(readFileSync(resolve(root, 'assets/brand/van-icon-geometry.json'), 'utf8'));
const { body, seam, bumper, lampL, lampR } = geometry;
const px = (v) => (v * 1024).toFixed(2);
const path = (pts, close = false) =>
  pts.map((p, i) => (i === 0 ? 'M' : 'L') + px(p[0]) + ',' + px(p[1])).join(' ') + (close ? 'Z' : '');
const stroke = (pts) => {
  const [a, b] = pts;
  return `M${px(a[0])},${px(a[1])} L${px(b[0])},${px(b[1])}`;
};
const lampRect = (pts) => {
  const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
  const x = Math.min(...xs), y = Math.min(...ys), w = Math.max(...xs) - x, h = Math.max(...ys) - y;
  return `<rect x="${px(x)}" y="${px(y)}" width="${px(w)}" height="${px(h)}" rx="${px(0.022)}" fill="#D8432F"/>`;
};
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <path d="${path(body, true)}" fill="#2B3644"/>
  <path d="${stroke([[body[1][0], body[1][1] + 0.028], [body[2][0], body[2][1] + 0.028]])}" stroke="#94B3D1" stroke-width="18" stroke-linecap="round"/>
  <path d="${stroke(seam)}" stroke="#94B3D1" stroke-width="13" stroke-linecap="round"/>
  <path d="${stroke(bumper)}" stroke="#94B3D1" stroke-width="16" stroke-linecap="round"/>
  ${lampRect(lampL)}
  ${lampRect(lampR)}
</svg>
`;
const svgPath = resolve(root, 'assets/brand/van-icon.svg');
writeFileSync(svgPath, svg);
const pngPath = resolve(root, 'assets/brand/app-icon-cutout.png');
await sharp(Buffer.from(svg), { density: 144 }).png().toFile(pngPath);

// The Dock assembly include: the same contours as C arrays.
const c = (name, pts) =>
  `static const CSPoint ${name}[] = {\n` +
  pts.map((p) => `    {${p[0].toFixed(3)},${p[1].toFixed(3)}}`).join(',\n') +
  '\n};';
const include = `// Generated by scripts/generate-van-icon-art.mjs from
// assets/brand/van-icon-geometry.json. Do not edit by hand; regenerate
// through \`npm run assets:icon\`.
${c('CSVanBody', body)}
${c('CSVanSeam', seam)}
${c('CSVanBumper', bumper)}
${c('CSVanLampL', lampL)}
${c('CSVanLampR', lampR)}
`;
writeFileSync(resolve(root, 'src-tauri/macos/DockTile/DockAssemblyGeometry.inc'), include);

console.log('Van icon art regenerated: svg, cut-out png, dock assembly geometry.');
console.log('sha256', createHash('sha256').update(readFileSync(pngPath)).digest('hex'));