// Derive the Dock assembly choreography from the captured icon render.
//
// scripts/capture-van-icon.mjs shoots the real van through the game's own
// renderer into assets/brand/app-icon-van-render.png. This script reads that
// frame and derives, nothing hand-drawn:
//
//   - the arrival field: for each cell, when its pixels appear, from the
//     silhouette's distance transform (outline draws, then the body fills
//     from its centre, exactly like the ear's analytic model, but measured
//     from the real render);
//   - the lamp boxes: the two largest red clusters in the frame, which the
//     running Dock assembly flashes at the end.
//
// Both are written to src-tauri/macos/DockTile/DockAssemblyGeometry.inc for
// the AppKit assembly to consume. Deterministic: same PNG, same include.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const png = resolve(root, 'assets/brand/app-icon-van-render.png');
const FIELD = 128;
const DURATION = 2700;

const { data, info } = await sharp(png).resize(FIELD, FIELD).raw().toBuffer({ resolveWithObject: true });
const { width: W, height: H, channels } = info;
const at = (x, y) => { const i = (y * W + x) * channels; return { r: data[i], g: data[i + 1], b: data[i + 2], a: channels > 3 ? data[i + 3] : 255 }; };

// Silhouette: opaque enough to belong to the van, and not obviously a lamp.
const silhouette = Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) => {
  const p = at(x, y);
  return p.a > 24 && !(p.r > 140 && p.g < 90 && p.b < 90);
}));

// Distance transform (two passes, city block) for the outline growth.
const dist = Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) => (silhouette[y][x] ? 0 : 1e9)));
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  if (y > 0) dist[y][x] = Math.min(dist[y][x], dist[y - 1][x] + 1);
  if (x > 0) dist[y][x] = Math.min(dist[y][x], dist[y][x - 1] + 1);
}
for (let y = H - 1; y >= 0; y--) for (let x = W - 1; x >= 0; x--) {
  if (y < H - 1) dist[y][x] = Math.min(dist[y][x], dist[y + 1][x] + 1);
  if (x < W - 1) dist[y][x] = Math.min(dist[y][x], dist[y][x + 1] + 1);
}

// The mass centre of the silhouette: the body fills from here.
let cx = 0, cy = 0, n = 0;
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (silhouette[y][x]) { cx += x; cy += y; n++; }
if (n === 0) throw new Error('the captured icon has no readable silhouette');
cx /= n; cy /= n;

// Arrival, in milliseconds: outline draws (0.22s + stroke position), then the
// interior fills from the mass centre; lamps resolve last (1.78s on).
const arrival = Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) => {
  const p = at(x, y);
  if (p.a <= 24) return DURATION;
  if (p.r > 140 && p.g < 90 && p.b < 90) return 1780 + (dist[y][x] / FIELD) * 200;
  const centre = Math.hypot(x - cx, y - cy) / FIELD;
  const rim = 220 + (1 - Math.min(1, dist[y][x] / 9)) * 800;
  return Math.min(1780, Math.min(50 + centre * 2400, rim));
}));

// Lamp boxes: red clusters in the frame, merged to at most two by x-centre.
const red = [];
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  const p = at(x, y);
  if (p.a > 24 && p.r > 140 && p.g < 90 && p.b < 90) red.push({ x, y });
}
if (red.length < 8) throw new Error('the captured icon has no lamp pixels');
const halves = [red.filter((p) => p.x < W / 2), red.filter((p) => p.x >= W / 2)];
const box = (points) => ({
  x: Math.min(...points.map((p) => p.x)) / W, y: Math.min(...points.map((p) => p.y)) / H,
  w: (Math.max(...points.map((p) => p.x)) - Math.min(...points.map((p) => p.x))) / W,
  h: (Math.max(...points.map((p) => p.y)) - Math.min(...points.map((p) => p.y))) / H,
});
const lamps = halves.filter((half) => half.length >= 4).map(box);
if (lamps.length !== 2) throw new Error(`expected two lamp clusters, found ${lamps.length}`);

const include = [
  '// Generated by scripts/generate-van-icon-art.mjs from the captured icon',
  '// render (scripts/capture-van-icon.mjs). Do not edit by hand; regenerate',
  '// through `npm run assets:icon`.',
  'static const NSUInteger CSVFieldSide = ' + FIELD + ';',
  'static const uint16_t CSVArrival[CSVFieldSide * CSVFieldSide] = {',
  ...arrival.map((row) => '    ' + row.join(',') + ','),
  '};',
  'static const CGRect CSVanishLamps[2] = {',
  ...lamps.map((l) => `    CGRectMake(${(l.x * 256).toFixed(1)},${(l.y * 256).toFixed(1)},${(l.w * 256).toFixed(1)},${(l.h * 256).toFixed(1)}),`),
  '};',
  '',
].join('\n');
writeFileSync(resolve(root, 'src-tauri/macos/DockTile/DockAssemblyGeometry.inc'), include);
console.log('Dock assembly geometry derived from the captured render.');
console.log('sha256', createHash('sha256').update(readFileSync(png)).digest('hex'));